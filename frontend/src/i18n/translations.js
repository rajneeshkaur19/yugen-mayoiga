export const SUPPORTED_LANGUAGES = [
  { code: 'EN', storyLanguage: 'English', label: 'English', native: 'English' },
  { code: 'JA', storyLanguage: 'Japanese', label: 'Japanese', native: '日本語' },
  { code: 'HI', storyLanguage: 'Hindi', label: 'Hindi', native: 'हिन्दी' },
  { code: 'FR', storyLanguage: 'French', label: 'French', native: 'Français' },
]

export function codeToStoryLanguage(code) {
  const found = SUPPORTED_LANGUAGES.find((l) => l.code === code)
  return found ? found.storyLanguage : 'English'
}

export function storyLanguageToCode(storyLanguage) {
  const found = SUPPORTED_LANGUAGES.find((l) => l.storyLanguage === storyLanguage)
  return found ? found.code : 'EN'
}

